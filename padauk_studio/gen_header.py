"""Generate the chip register header (e.g. pfs154.h) from the chip database."""

from .chips import Chip


def _c_name(chip: Chip) -> str:
    return chip.name.lower() + ".h"


def header_name(chip: Chip) -> str:
    return _c_name(chip)


def generate_header(chip: Chip) -> str:
    L = []
    w = L.append
    guard = f"PDK_{chip.name}_H"
    w(f"/* {header_name(chip)}: registers of the {chip.name}.")
    w(f" * Generated by Padauk Studio from its chip database ({chip.datasheet}).")
    w(" * Don't edit: it's rewritten when you press Generate.")
    w(" *")
    w(" * Names: REG is the register, REG_FIELD a 1-bit field mask, REG_FIELD_VALUE a")
    w(" * value of a wider field, already shifted into place.")
    w(" */")
    w(f"#ifndef {guard}")
    w(f"#define {guard}")
    w("")
    w(f"#if !defined(__SDCC_{chip.arch})")
    w(f'#error "The {chip.name} needs sdcc -m{chip.arch}"')
    w("#endif")
    w("")
    w("#include <stdint.h>")
    w("")
    w(f"#define CHIP_{chip.name}        1")
    w(f'#define CHIP_NAME          "{chip.name}"')
    w(f"#define CHIP_ROM_WORDS     {chip.rom_words}")
    w(f"#define CHIP_RAM_BYTES     {chip.ram_bytes}")
    w(f"#define ILRC_HZ            {chip.ilrc_hz}UL   /* typical, varies with VDD and temperature */")
    w("")
    w("/* ---- Registers ---------------------------------------------------------- */")
    for r in sorted(chip.registers, key=lambda r: r.addr):
        src = f"datasheet {r.section}" if r.source == "datasheet" else "not in the datasheet: free-pdk"
        acc = {"wo": ", write only", "ro": ", read only"}.get(r.access, "")
        w(f"__sfr __at(0x{r.addr:02x}) _{r.name.lower()};")
        w(f"#define {r.name:<14} _{r.name.lower()}    /* {r.doc} ({src}{acc}) */")
        w(f"#define {r.name + '_ADDR':<14} 0x{r.addr:02x}")
    w("")
    w("/* Timer16 counter: read with T16C = ... / ... = T16C (ldt16 / stt16) */")
    w("__sfr16 _t16c;")
    w("#define T16C _t16c")
    w("")
    w("/* ---- Register bits ------------------------------------------------------ */")
    for r in sorted(chip.registers, key=lambda r: r.addr):
        if not r.fields and not r.consts:
            continue
        w(f"/* {r.name}: {r.doc} */")
        for f in r.fields:
            base = f"{r.name}_{f.name}"
            doc = f"   /* {f.doc} */" if f.doc else ""
            if f.width == 1 and not f.values:
                w(f"#define {base:<28} (1 << {f.pos}){doc}")
                continue
            w(f"#define {base + '_POS':<28} {f.pos}{doc}")
            w(f"#define {base + '_MASK':<28} (0x{(1 << f.width) - 1:x} << {f.pos})")
            for vname, v in f.values.items():
                w(f"#define {base + '_' + vname:<28} ({v} << {f.pos})")
        for cname, v in r.consts.items():
            w(f"#define {cname:<28} 0x{v:02x}")
        w("")
    w("/* ---- Fuse word (written with the program) -------------------------------- */")
    w(f"#define FUSE_ADDR          0x{chip.fuse_addr:03x}")
    w(f"#define FUSE_RESERVED      0x{chip.fuse_reserved:04x}   /* bits that must be 1 */")
    for opt, choices in chip.fuse_bits.items():
        for ch, bits in choices.items():
            w(f"#define FUSE_{opt.upper()}_{ch.upper():<10} 0x{bits:04x}")
    w("#define PDK_FUSE(bits) __asm__(\".area FUSE (ABS)\\n.org (\" PDK_STR(FUSE_ADDR) \"*2)\\n"
      ".word (\" PDK_STR(FUSE_RESERVED) \"|\" PDK_STR(bits) \")\\n.area CODE\\n\")")
    w("")
    if chip.factory_ihrcr is not None or chip.factory_bgtr is not None:
        w("/* Factory calibration values: RET k instructions near the end of ROM */")
        w("typedef uint8_t (*pdk_factory_fn)(void);")
        if chip.factory_ihrcr is not None:
            w(f"#define FACTORY_IHRCR()    (((pdk_factory_fn)0x{chip.factory_ihrcr:03x})())")
        if chip.factory_bgtr is not None:
            w(f"#define FACTORY_BGTR()     (((pdk_factory_fn)0x{chip.factory_bgtr:03x})())")
        w("")
    w("/* ---- CPU instructions ---------------------------------------------------- */")
    w('#define PDK_STR_(x)        #x')
    w('#define PDK_STR(x)         PDK_STR_(x)')
    w('#define nop()              __asm__("nop\\n")')
    w('#define interrupts_on()    __asm__("engint\\n")')
    w('#define interrupts_off()   __asm__("disgint\\n")')
    w('#define stopsys()          __asm__("stopsys\\n")       /* power down until a pin changes */')
    w('#define stopexe()          __asm__("stopexe\\nnop\\n")  /* stop the CPU, clocks keep running */')
    w('#define wdt_reset()        __asm__("wdreset\\n")')
    w('#define chip_reset()       __asm__("reset\\n")')
    w("")
    w("/* Easy PDK calibration placeholder: easypdkprog finds this pattern and")
    w(" * replaces it with code that tunes the oscillator to `freq` at `mv` millivolts. */")
    w("#define PDK_CALIBRATE(type, reg, freq, mv) __asm__( \\")
    w('  "and a, #\'R\'\\n" "and a, #\'C\'\\n" "and a, #(" PDK_STR(type) ")\\n" \\')
    w('  "and a, #((" PDK_STR(freq) "))\\n" "and a, #((" PDK_STR(freq) ")>>8)\\n" \\')
    w('  "and a, #((" PDK_STR(freq) ")>>16)\\n" "and a, #((" PDK_STR(freq) ")>>24)\\n" \\')
    w('  "and a, #((" PDK_STR(mv) "))\\n" "and a, #((" PDK_STR(mv) ")>>8)\\n" \\')
    w('  "and a, #(" PDK_STR(reg) ")\\n")')
    w("#define PDK_CALIBRATE_IHRC(freq, mv)  PDK_CALIBRATE(1, IHRCR_ADDR, freq, mv)")
    if any(r.name == "ILRCR" for r in chip.registers):
        w("#define PDK_CALIBRATE_ILRC(freq, mv)  PDK_CALIBRATE(2, ILRCR_ADDR, freq, mv)")
    w("")
    if chip.extra_header:
        w(chip.extra_header)
    w(f"#endif /* {guard} */")
    return "\n".join(L) + "\n"
